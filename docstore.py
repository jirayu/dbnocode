"""JSON document store on Firebird 5 for deeply nested master / detail /
sub-detail documents.

Documents are stored whole as one row in NC_DOC; scalar leaves are flattened
into NC_IDX so Firebird can query inside JSON (which it cannot do natively).

Tables:
  NC_DOC(ID, ENTITY, DOC_KEY, BODY, VER, UPDATED) -- one row per document
  NC_IDX(DOC_ID, ENTITY, PATH, ARR, VS, VN)       -- flattened scalar leaves

DOC_KEY = optional string key (e.g. the document's ``id`` field) so the
          no-code engine can upsert by human-readable key instead of the
          internal BIGINT surrogate.
PATH  = wildcard path, e.g. "lines[].sku", "lines[].subs[].code", "customer"
ARR   = instance address of the nearest enclosing array element,
        e.g. "lines.1.subs.0"; "" for root-level scalars.
VS    = string value (varchar(100)); VN = numeric value (numeric(18,4)).

The database must be created with PAGE_SIZE=16384 (index key length limit).

Usage:

    db = DocStore("localhost:/data/nocode.fdb")
    # db.create_schema()   # run once to create NC_DOC + NC_IDX

    did, ver = db.save("order", {
        "customer": "Somchai",
        "date": "2026-11-07",
        "lines": [
            {"sku": "A1", "qty": 2, "subs": [{"code": "X", "qty": 5}]},
            {"sku": "B7", "qty": 9, "subs": [{"code": "Y", "qty": 1},
                                             {"code": "X", "qty": 8}]},
        ],
    })

    # same line: sku B7 AND qty > 5
    db.find("order", [("lines[].sku", "=", "B7"), ("lines[].qty", ">", 5)])

    # sub-line belongs to matched line: line B7 whose sub code is X
    db.find("order", [("lines[].sku", "=", "B7"),
                       ("lines[].subs[].code", "=", "X")])

    # header + deep value
    db.find("order", [("customer", "=", "Somchai"),
                      ("lines[].subs[].qty", ">=", 8)])

    # upsert by string key
    db.save("item", {"name": "Widget"}, key="ITEM-001")
"""
from __future__ import annotations

import json
import os
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Dict, Iterable, List, Optional, Sequence, Tuple


# ---------------------------------------------------------------------------
# DDL
# ---------------------------------------------------------------------------

DDL: List[str] = [
    """CREATE TABLE NC_DOC (
  ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ENTITY VARCHAR(64) NOT NULL,
  DOC_KEY VARCHAR(255) CHARACTER SET UTF8,
  BODY BLOB SUB_TYPE TEXT CHARACTER SET UTF8 NOT NULL,
  VER INTEGER DEFAULT 1 NOT NULL,
  UPDATED TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL)""",
    "CREATE INDEX IX_DOC_ENT ON NC_DOC (ENTITY)",
    "CREATE UNIQUE INDEX IX_DOC_KEY ON NC_DOC (ENTITY, DOC_KEY)",
    """CREATE TABLE NC_IDX (
  DOC_ID BIGINT NOT NULL REFERENCES NC_DOC(ID) ON DELETE CASCADE,
  ENTITY VARCHAR(64) NOT NULL,
  PATH   VARCHAR(100) NOT NULL,
  ARR    VARCHAR(100) NOT NULL,
  VS     VARCHAR(100) CHARACTER SET UTF8,
  VN     NUMERIC(18,4))""",
    "CREATE INDEX IX_I_DOC ON NC_IDX (DOC_ID)",
    "CREATE INDEX IX_I_S ON NC_IDX (ENTITY, PATH, VS)",
    "CREATE INDEX IX_I_N ON NC_IDX (ENTITY, PATH, VN)",
    "CREATE INDEX IX_I_ARR ON NC_IDX (ENTITY, PATH, ARR)",
]

# ---------------------------------------------------------------------------
# Index registry
# ---------------------------------------------------------------------------

# Per-entity indexed wildcard paths.  A missing entity (or None) means
# "index every scalar leaf".
REGISTRY: Dict[str, Optional[Iterable[str]]] = {
    # Empty by default -- all tables index every scalar leaf.
    # Add entries here to restrict indexing to specific paths.
}

# Whitelisted comparison operators -> Firebird SQL.
OPS: Dict[str, str] = {
    "=": "=", "<>": "<>", ">": ">", "<": "<",
    ">=": ">=", "<=": "<=", "starts": "STARTING WITH",
}


def _configure_firebird_client() -> None:
    """Point firebird-driver at the 64-bit client on Windows.

    A bare ``connect()`` may pick ``C:\\Windows\\System32\\fbclient.dll``
    (often the wrong architecture).
    """
    if os.name != "nt":
        return
    candidates = [
        os.environ.get("FIREBIRD_CLIENT_LIB", ""),
        os.environ.get("NOCODE_FB_CLIENT", ""),
    ]
    for base in (
        os.environ.get("ProgramFiles", r"C:\Program Files"),
        os.environ.get("ProgramFiles(x86)", r"C:\Program Files (x86)"),
    ):
        if not base:
            continue
        root = Path(base) / "Firebird"
        if root.is_dir():
            for folder in sorted(root.glob("Firebird_*"), reverse=True):
                candidates.append(str(folder / "fbclient.dll"))
            candidates.append(str(root / "fbclient.dll"))
    for candidate in candidates:
        if candidate and os.path.isfile(candidate):
            try:
                from firebird.driver import driver_config
                driver_config.fb_client_library.value = candidate
            except Exception:
                pass
            return


class ConcurrencyError(Exception):
    """Raised when an optimistic-lock update conflicts (document changed)."""


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

@dataclass(frozen=True)
class Row:
    path: str
    arr: str
    value: Any

    def __eq__(self, other):
        if isinstance(other, tuple) and len(other) == 3:
            return self.path == other[0] and self.arr == other[1] and self.value == other[2]
        return NotImplemented

    def __hash__(self):
        return hash((self.path, self.arr, self.value))


def _text(v: Any) -> str:
    """Return a BLOB value as a str, handling file-like objects and bytes."""
    if hasattr(v, "read"):
        v = v.read()
    if isinstance(v, (bytes, bytearray)):
        return v.decode("utf-8")
    return v if isinstance(v, str) else str(v)


def flatten(doc: Any, wanted: Optional[Iterable[str]] = None) -> List[Row]:
    """Return one Row per scalar leaf in a nested document.

    ``wanted`` is a set of wildcard paths.  ``None`` means all scalar leaves.
    Array positions are rebuilt on every save, so deleting or reordering lines
    never leaves stale ARR values.
    """
    wanted_set = set(wanted) if wanted is not None else None
    rows: List[Row] = []

    def walk(node: Any, path: str, arr: str) -> None:
        if isinstance(node, dict):
            for key, value in node.items():
                child = f"{path}.{key}" if path else str(key)
                walk(value, child, arr)
        elif isinstance(node, (list, tuple)):
            if arr:
                field_name = path.rsplit(".", 1)[-1]
                base = f"{arr}.{field_name}"
            else:
                base = path
            for index, item in enumerate(node):
                walk(item, f"{path}[]", f"{base}.{index}")
        elif node is not None:
            if wanted_set is None or path in wanted_set:
                rows.append(Row(path, arr, node))

    walk(doc, "", "")
    return rows


def scope_of(path: str) -> str:
    """Return the array scope of a wildcard path.

    ``lines[].subs[].code`` -> ``lines[].subs[]``
    ``customer`` -> ``""``
    """
    i = path.rfind("[]")
    return path[:i + 2] if i >= 0 else ""


def _index_value(value) -> Tuple[str, Optional[float], str]:
    """Return ``(vs, vn, indicator)`` for one index row."""
    if isinstance(value, bool):
        return ("true" if value else "false"), (1.0 if value else 0.0), "n"
    if isinstance(value, (int, float)):
        return str(value), float(value), "n"
    return str(value)[:100], None, "s"


# ---------------------------------------------------------------------------
# Document store
# ---------------------------------------------------------------------------

class DocStore:
    """Firebird-backed JSON document store for nested master/detail docs.

    Parameters
    ----------
    dsn:
        Firebird DSN, e.g. ``"localhost:/data/nocode.fdb"`` or
        ``"/data/nocode.fdb"`` for a local (embedded) connection.
    user, password:
        Firebird credentials.
    registry:
        Per-entity indexed paths.  Defaults to module-level ``REGISTRY``.
    charset:
        Firebird connection charset.
    """

    def __init__(self, dsn: str, user: str = "SYSDBA",
                 password: str = "masterkey", *,
                 registry: Optional[Dict[str, Optional[Iterable[str]]]] = None,
                 charset: str = "UTF8"):
        _configure_firebird_client()
        from firebird.driver import connect  # type: ignore
        self.registry = REGISTRY if registry is None else registry
        self._con = connect(dsn, user=user, password=password, charset=charset)
        self._con.autocommit = False

    # -- connection management ----------------------------------------------

    @property
    def con(self):
        return self._con

    def close(self) -> None:
        if self._con is not None:
            try:
                self._con.close()
            except Exception:
                pass
            self._con = None

    def __enter__(self) -> "DocStore":
        return self

    def __exit__(self, exc_type, exc, tb) -> None:
        if exc_type is None:
            try:
                self._con.commit()
            except Exception:
                pass
        else:
            try:
                self._con.rollback()
            except Exception:
                pass
        self.close()
        return False

    # -- schema -------------------------------------------------------------

    def create_schema(self) -> None:
        """Create NC_DOC, NC_IDX and their indexes (idempotent)."""
        cur = self._con.cursor()
        cur.execute(
            "select count(*) from rdb$relations where rdb$relation_name = 'NC_DOC'"
        )
        doc_exists = bool(cur.fetchone()[0])
        cur.execute(
            "select count(*) from rdb$relations where rdb$relation_name = 'NC_IDX'"
        )
        idx_exists = bool(cur.fetchone()[0])
        if not doc_exists:
            self._con.execute_immediate(DDL[0])
            self._con.execute_immediate(DDL[1])
            self._con.execute_immediate(DDL[2])
        else:
            # Existing installs predate DOC_KEY for string IDs.
            cur.execute(
                "select count(*) from rdb$relation_fields "
                "where rdb$relation_name = 'NC_DOC' and rdb$field_name = 'DOC_KEY'"
            )
            if not cur.fetchone()[0]:
                self._con.execute_immediate(
                    "alter table NC_DOC add DOC_KEY VARCHAR(255) CHARACTER SET UTF8"
                )
                self._con.execute_immediate(
                    "create unique index IX_DOC_KEY on NC_DOC (ENTITY, DOC_KEY)"
                )
                self._con.commit()
        if not idx_exists:
            for sql in DDL[3:]:
                self._con.execute_immediate(sql)
        self._con.commit()

    # -- indexing -----------------------------------------------------------

    def _index(self, cur, doc_id: int, entity: str, doc: Any,
               wanted: Optional[Iterable[str]] = None) -> None:
        """Insert flattened scalar leaves for *doc* into NC_IDX."""
        if wanted is None:
            wanted = self.registry.get(entity)
        for row in flatten(doc, wanted):
            vs, vn, kind = _index_value(row.value)
            if kind == "n":
                cur.execute(
                    "INSERT INTO NC_IDX "
                    "(DOC_ID, ENTITY, PATH, ARR, VN) VALUES (?, ?, ?, ?, ?)",
                    (doc_id, entity, row.path[:100], row.arr[:100], vn),
                )
            else:
                cur.execute(
                    "INSERT INTO NC_IDX "
                    "(DOC_ID, ENTITY, PATH, ARR, VS) VALUES (?, ?, ?, ?, ?)",
                    (doc_id, entity, row.path[:100], row.arr[:100], vs),
                )

    # -- save / load / delete ----------------------------------------------

    def save(self, entity: str, doc: Dict[str, Any],
             doc_id: Optional[int] = None, ver: Optional[int] = None, *,
             key: Optional[str] = None,
             commit: bool = True) -> Tuple[int, int]:
        """Insert or update a document.

        On insert, returns ``(doc_id, ver=1)``.
        On update, uses optimistic locking: ``WHERE ID=? AND VER=?``; raises
        :class:`ConcurrencyError` if the document was changed by another
        transaction.  Returns ``(doc_id, new_ver)``.

        Parameters
        ----------
        key:
            Optional human-readable key stored in DOC_KEY.  When given on
            insert and a row with this key already exists, the call turns
            into an update (upsert).
        commit:
            If ``False``, the transaction is left open so multiple saves can
            be chained and committed together.
        """
        entity = str(entity or "").strip()
        if not entity:
            raise ValueError("entity is required")
        if not isinstance(doc, dict):
            raise TypeError("doc must be a dict")
        key_text = str(key).strip() if key is not None else None
        cur = self._con.cursor()
        try:
            body = json.dumps(doc, ensure_ascii=False)
            if doc_id is None and key_text is not None:
                cur.execute(
                    "SELECT ID, VER FROM NC_DOC WHERE ENTITY=? AND DOC_KEY=?",
                    (entity, key_text),
                )
                found = cur.fetchone()
                if found:
                    doc_id, ver = int(found[0]), int(found[1])
            if doc_id is None:
                cur.execute(
                    "INSERT INTO NC_DOC (ENTITY, DOC_KEY, BODY) "
                    "VALUES (?, ?, ?) RETURNING ID",
                    (entity, key_text, body),
                )
                doc_id = int(cur.fetchone()[0])
                ver = 1
            else:
                if ver is None:
                    raise ValueError("ver is required when updating a document")
                cur.execute(
                    "UPDATE NC_DOC SET DOC_KEY=?, BODY=?, VER=VER+1, "
                    "UPDATED=CURRENT_TIMESTAMP WHERE ID=? AND VER=?",
                    (key_text, body, doc_id, ver),
                )
                if cur.rowcount != 1:
                    raise ConcurrencyError(
                        f"{entity} {doc_id} changed by someone else"
                    )
                ver = int(ver) + 1
                cur.execute("DELETE FROM NC_IDX WHERE DOC_ID=?", (doc_id,))

            self._index(cur, doc_id, entity, doc)

            if commit:
                self._con.commit()
            return int(doc_id), int(ver)
        except Exception:
            try:
                self._con.rollback()
            except Exception:
                pass
            raise

    def load(self, doc_id: int) -> Optional[Dict[str, Any]]:
        """Load a document by ID.  Returns None if not found."""
        cur = self._con.cursor()
        cur.execute(
            "SELECT ENTITY, DOC_KEY, BODY, VER FROM NC_DOC WHERE ID=?",
            (doc_id,),
        )
        row = cur.fetchone()
        if not row:
            return None
        return {
            "id": int(doc_id),
            "entity": row[0],
            "key": row[1],
            "ver": int(row[3]),
            "data": json.loads(_text(row[2])),
        }

    def load_key(self, entity: str, key: str) -> Optional[Dict[str, Any]]:
        """Load a document by entity + DOC_KEY.  Returns None if not found."""
        cur = self._con.cursor()
        cur.execute(
            "SELECT ID FROM NC_DOC WHERE ENTITY=? AND DOC_KEY=?",
            (str(entity), str(key)),
        )
        row = cur.fetchone()
        return self.load(int(row[0])) if row else None

    def delete(self, doc_id: int, *, commit: bool = True) -> None:
        """Delete a document (NC_IDX rows cascade via FK ON DELETE CASCADE)."""
        self._con.cursor().execute("DELETE FROM NC_DOC WHERE ID=?", (doc_id,))
        if commit:
            self._con.commit()

    def delete_key(self, entity: str, key: str, *, commit: bool = True) -> None:
        """Delete a document by entity + DOC_KEY."""
        self._con.cursor().execute(
            "DELETE FROM NC_DOC WHERE ENTITY=? AND DOC_KEY=?",
            (str(entity), str(key)),
        )
        if commit:
            self._con.commit()

    def commit(self) -> None:
        """Commit the current transaction."""
        self._con.commit()

    def rollback(self) -> None:
        """Roll back the current transaction."""
        self._con.rollback()

    def reindex_all(self, entity: str) -> int:
        """Rebuild NC_IDX for all documents of *entity*.

        Call this after REGISTRY gains a new indexed path for an entity.
        Returns the number of documents reindexed.
        """
        cur = self._con.cursor()
        cur.execute("SELECT ID, BODY FROM NC_DOC WHERE ENTITY=?", (entity,))
        rows = [(int(i), json.loads(_text(b))) for i, b in cur.fetchall()]
        cur.execute("DELETE FROM NC_IDX WHERE ENTITY=?", (entity,))
        wanted = self.registry.get(entity, None)
        for doc_id, doc in rows:
            self._index(cur, doc_id, entity, doc, wanted)
        self._con.commit()
        return len(rows)

    # -- migration from flat tables -----------------------------------------

    def migrate_from_flat(self, adapter: Any, table_name: str, entity: str,
                          legacy_field: str = "_legacy_rowid",
                          batch_size: int = 100) -> Tuple[int, int]:
        """Migrate rows from a flat JSON table into this DocStore.

        Reads ``SELECT rowid, data FROM "<table_name>"`` from *adapter*, parses
        each JSON blob, and saves it under *entity*.  The original rowid is
        stored under *legacy_field* (set to ``None`` to skip).

        Commits in batches of *batch_size*.  Returns ``(migrated, errors)``.
        Works with any adapter that exposes ``query(sql) -> List[Dict]``,
        including :class:`dsl_lib.adapters.FirebirdAdapter`.
        """
        rows = adapter.query(f'SELECT rowid, data FROM "{table_name}"')
        migrated = 0
        errors = 0

        for i, row in enumerate(rows):
            try:
                raw = row.get("data", "")
                if hasattr(raw, "read"):
                    raw = raw.read()
                if isinstance(raw, bytes):
                    raw = raw.decode("utf-8", errors="replace")
                doc = json.loads(raw) if isinstance(raw, str) else raw
                if not isinstance(doc, dict):
                    errors += 1
                    continue

                old_rowid = row.get("rowid")
                if legacy_field and old_rowid is not None:
                    doc[legacy_field] = old_rowid

                commit = ((i + 1) % batch_size == 0)
                self.save(entity, doc, commit=commit)
                migrated += 1
            except Exception:
                errors += 1

        # Commit any remaining uncommitted rows from a partial batch.
        if migrated > 0 and migrated % batch_size != 0:
            self._con.commit()

        return migrated, errors

    # -- find ---------------------------------------------------------------

    def find(self, entity: str, conds: Sequence[Tuple[str, str, Any]],
             limit: int = 100) -> List[int]:
        """Find document IDs matching all conditions (AND-ed).

        Matching rules
        --------------
        * Conditions in the same array scope must match the SAME element
          (equal ARR).
        * A deeper scope is linked to the nearest shallower scope in the query
          using ``ARR STARTING WITH parent.ARR || '.'``.
        * Numeric values query ``VN``; strings query ``VS``.
        """
        rows_list = list(conds or [])
        if limit <= 0:
            return []

        if not rows_list:
            cur = self._con.cursor()
            cur.execute(
                "SELECT FIRST ? d.ID FROM NC_DOC d WHERE d.ENTITY=? "
                "ORDER BY d.ID",
                (limit, entity),
            )
            return [r[0] for r in cur.fetchall()]

        first_in_scope: Dict[str, str] = {}
        joins: List[str] = []
        from_parts: List[str] = []
        args: List[Any] = [entity]

        for n, (path, op, val) in enumerate(rows_list):
            path = str(path or "").strip()
            if not path:
                raise ValueError("condition path is required")
            if op not in OPS:
                raise ValueError(f"unsupported operator: {op!r}")
            alias = f"c{n}"
            from_parts.append(f"NC_IDX {alias}")
            if joins:
                joins.append("AND")
            joins.append(
                f"{alias}.DOC_ID=d.ID AND {alias}.ENTITY=? AND "
                f"{alias}.PATH=?"
            )
            args.extend([entity, path])
            if isinstance(val, bool):
                joins.append(f"AND {alias}.VN {OPS[op]} ?")
                args.append(1.0 if val else 0.0)
            elif isinstance(val, (int, float)):
                joins.append(f"AND {alias}.VN {OPS[op]} ?")
                args.append(float(val))
            else:
                joins.append(f"AND {alias}.VS {OPS[op]} ?")
                args.append(str(val)[:100])

            sc = scope_of(path)
            if sc:
                if sc in first_in_scope:
                    joins.append(f"AND {alias}.ARR={first_in_scope[sc]}.ARR")
                else:
                    parents = [s for s in first_in_scope
                               if s and sc.startswith(s) and s != sc]
                    if parents:
                        parent_scope = max(parents, key=len)
                        parent_alias = first_in_scope[parent_scope]
                        joins.append(
                            f"AND {alias}.ARR STARTING WITH "
                            f"{parent_alias}.ARR || '.'"
                        )
                    first_in_scope[sc] = alias

        sql = (f"SELECT FIRST {int(limit)} d.ID FROM NC_DOC d "
               f"WHERE d.ENTITY=?")
        if from_parts:
            sql += (f" AND EXISTS (SELECT 1 FROM {', '.join(from_parts)} "
                    f"WHERE {' '.join(joins)})")
        sql += " ORDER BY d.ID"

        cur = self._con.cursor()
        cur.execute(sql, tuple(args))
        return [int(r[0]) for r in cur.fetchall()]
